function HourTracker() {
  const [start, setStart] = useState<string>(() =>
    typeof window === "undefined" ? "" : localStorage.getItem("fc_event_start") ?? "");
  const [now, setNow] = useState(0);
  useEffect(() => {
    const kick = setTimeout(() => setNow(Date.now()), 0);
    const t = setInterval(() => setNow(Date.now()), 30000);
    return () => { clearTimeout(kick); clearInterval(t); };
  }, []);
  const hrs = start ? (now - new Date(start).getTime()) / 3600000 : null;
  const toDeadline = hrs == null ? null : 20 - hrs;
  return (
    <div className="rounded-3xl bg-slate-950 text-white p-6">
      <h3 className="font-black flex items-center gap-2"><Hourglass className="w-5 h-5 text-cyan-400" /> Event clock (Hour 20 = hard deadline)</h3>
      <div className="flex flex-col sm:flex-row gap-3 mt-4">
        <input type="datetime-local" value={start} onChange={(e) => { setStart(e.target.value); localStorage.setItem("fc_event_start", e.target.value); }}
          className="rounded-xl bg-white/10 border border-white/20 px-3 py-2.5 text-sm flex-1" aria-label="Event start (Hour 0)" />
        <button className="rounded-xl bg-white/10 px-4 py-2.5 text-sm font-bold" onClick={() => { const v = new Date().toISOString().slice(0, 16); setStart(v); localStorage.setItem("fc_event_start", v); }}>Set Hour 0 = now</button>
      </div>
      {hrs != null && Number.isFinite(hrs) ? (
        <div className="mt-4">
          <div className="flex justify-between text-sm font-bold"><span>Elapsed: Hour {hrs.toFixed(1)} / 24</span>
            <span className={toDeadline! < 0 ? "text-red-400" : toDeadline! < 2 ? "text-amber-300" : "text-emerald-300"}>
              {toDeadline! >= 0 ? `${toDeadline!.toFixed(1)}h to Hour-20 deadline` : `PAST DEADLINE by ${Math.abs(toDeadline!).toFixed(1)}h`}</span></div>
          <div className="h-3 rounded-full bg-white/10 mt-2 overflow-hidden">
            <div className="h-full bg-gradient-to-r from-cyan-500 to-red-500" style={{ width: `${Math.min(100, (hrs / 24) * 100)}%` }} /></div>
          <div className="flex justify-between text-[11px] text-slate-400 mt-1"><span>H0</span><span>H6 check-in</span><span className="text-red-300 font-bold">H20 DEADLINE</span><span>H24</span></div>
        </div>) : <p className="text-slate-400 text-sm mt-3">Set your Hour-0 release time to start the countdown.</p>}
    </div>
  );
}

function Validator() {
  const [predText, setPredText] = useState(""); const [testText, setTestText] = useState("");
  const result = useMemo(() => {
    if (!predText.trim()) return null;
    const raw = parseCsv(predText);
    const headers = raw.length ? Object.keys(raw[0]) : [];
    if (headers.join(",") !== "station_id,date,discharge_cfs")
      return { errors: [`Columns must be exactly [station_id,date,discharge_cfs] in this order; got [${headers.join(",")}]`], warnings: [] as string[], n: raw.length };
    const preds = raw.map((r) => ({ station_id: (r.station_id ?? "").padStart(8, "0"), date: String(r.date ?? "").slice(0, 10), discharge_cfs: parseFloat(r.discharge_cfs ?? "") }));
    const test = testText.trim() ? parseCsv(testText) : undefined;
    return { ...validatePredictions(preds, test), n: preds.length };
  }, [predText, testText]);
  const read = (setter: (s: string) => void) => async (f?: File | null) => { if (f) setter(await f.text()); };
  return (
    <div className="rounded-3xl border border-slate-200 bg-white p-6 shadow-sm">
      <h3 className="font-black text-lg flex items-center gap-2"><FileCheck2 className="w-5 h-5 text-cyan-700" /> Validate predictions.csv (Brief §5 rules)</h3>
      <div className="grid md:grid-cols-2 gap-4 mt-5">
        <div><label className={labelCls}>PREDICTIONS.CSV</label>
          <label className={btnGhost + " w-full cursor-pointer mb-2"}>Upload predictions.csv<input type="file" accept=".csv" className="hidden" onChange={(e) => read(setPredText)(e.target.files?.[0])} /></label>
          <textarea rows={5} className={inputCls + " font-mono text-xs"} value={predText} onChange={(e) => setPredText(e.target.value)} placeholder="station_id,date,discharge_cfs&#10;01646500,2023-08-10,1234.56" /></div>
        <div><label className={labelCls}>TEST.CSV (OPTIONAL — ENABLES COVERAGE CHECK)</label>
          <label className={btnGhost + " w-full cursor-pointer mb-2"}>Upload test.csv<input type="file" accept=".csv" className="hidden" onChange={(e) => read(setTestText)(e.target.files?.[0])} /></label>
          <textarea rows={5} className={inputCls + " font-mono text-xs"} value={testText} onChange={(e) => setTestText(e.target.value)} placeholder="station_id,date,..." /></div>
      </div>
      {result && <div className="mt-4 space-y-2">
        <div className={`rounded-xl px-4 py-3 text-sm font-bold flex items-center gap-2 ${result.errors.length ? "bg-red-50 text-red-800" : "bg-emerald-50 text-emerald-800"}`}>
          {result.errors.length ? <ShieldAlert className="w-4 h-4" /> : <ShieldCheck className="w-4 h-4" />}
          {result.errors.length ? `REJECTED — ${result.errors.length} problem(s) in ${result.n} rows` : `VALID — ${result.n} rows pass every Brief §5 check${testText ? " incl. full test.csv coverage" : ""}.`}
        </div>
        {result.errors.map((e, i) => <p key={i} className="text-sm text-red-700">✗ {e}</p>)}
        {result.warnings.map((w, i) => <p key={i} className="text-sm text-amber-700">⚠ {w}</p>)}
      </div>}
    </div>
  );
}

